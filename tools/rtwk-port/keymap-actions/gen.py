"""Generates core/src/features/settings/keymap_actions.rs from the oracle's action catalogue
(codex-rs/tui/src/keymap_setup/actions.rs, the `define_keymap_actions!` table): context, context
label, action, description and the feature gate of every action the /keymap picker lists.

Run from the repository root: python3 -I tools/rtwk-port/keymap-actions/gen.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SRC = ROOT / "codex-rs/tui/src/keymap_setup/actions.rs"
OUT = ROOT / "codex-rs/tui-rtwk/core/src/features/settings/keymap_actions.rs"

text = SRC.read_text()
start = text.index("define_keymap_actions! {")
body = text[start:]
context = re.compile(r'^\s{4}(\w+) "([^"]*)" \{$')
action = re.compile(r'^\s{8}(\w+)(?: \[(\w+)\])? => ("(?:[^"\\]|\\.)*"),$')
rows = []
label = ident = None
for line in body.splitlines()[1:]:
    if line.startswith("}"):
        break
    m = context.match(line)
    if m:
        ident, label = m.group(1), m.group(2)
        continue
    m = action.match(line)
    if m:
        gate = m.group(2)
        rows.append((ident, label, m.group(1), m.group(3), gate))
        continue
    stripped = line.strip()
    if stripped and stripped != "}" and not stripped.startswith("//"):
        sys.exit(f"unparsed line: {line!r}")

out = [
    "//! GENERATED by tools/rtwk-port/keymap-actions/gen.py from the oracle's",
    "//! `keymap_setup/actions.rs`; do not edit by hand.",
    "",
    "use super::keymap::{Action, Gate};",
    "",
    "pub const ACTIONS: &[Action] = &[",
]
for ident, label, name, desc, gate in rows:
    g = f"Some(Gate::{gate})" if gate else "None"
    out.append(
        f'    Action {{ context: "{ident}", context_label: "{label}", name: "{name}", '
        f"description: {desc}, gate: {g} }},"
    )
out.append("];")
OUT.write_text("\n".join(out) + "\n")
print(len(rows), "actions")
