#!/usr/bin/env python3
"""Writes `codex-rs/tui-rtwk/src/app/theme/syntax/models.rs`: the scopes of the oracle's six
model-named themes (`codex-rs/tui/assets/themes/*.tmTheme`: ada, babbage, curie, cushman, dali,
davinci), in the shape of the generated `scopes.rs` (the scopes the screens ask for, those the
bundled themes give), plus `codex.accent`, the scope `style::accent_style` reads. A scope takes
the rule whose selector is its longest prefix (on dot boundaries), the later rule on a tie, as
syntect's `style_mod_for_stack(&[scope])` does for a one-scope stack.
Run `python3 -I` from the repo root; the result is committed."""
import pathlib
import plistlib
import re

ROOT = pathlib.Path("codex-rs")
THEMES = ["ada", "babbage", "curie", "cushman", "dali", "davinci"]
OUT = ROOT / "tui-rtwk/src/app/theme/syntax/models.rs"
KNOWN = (ROOT / "tui-rtwk/src/app/theme/syntax/scopes.rs").read_text()
FG = ["markup.heading.%d.markdown" % n for n in range(1, 7)] + [
    "markup.heading.markdown",
    "markup.raw.inline.markdown",
    "markup.italic.markdown",
    "markup.bold.markdown",
    "markup.quote.markdown",
    "markup.underline.link.markdown",
    "markup.list.numbered.markdown",
    "markup.list.unnumbered.markdown",
    "markup.list.bullet.markdown",
    "markup.inline.raw.string.markdown",
    "entity.name.type",
    "support.type",
    "variable",
    "codex.accent",
]
BG = ["markup.inserted", "markup.deleted"]
for scope in FG[:-1] + BG:
    assert f'"{scope}"' in KNOWN, scope


def rules(theme):
    out = []
    for index, rule in enumerate(theme["settings"]):
        for selector in rule.get("scope", "").split(","):
            selector = selector.strip()
            if selector:
                out.append((len(selector.split(".")), index, selector, rule["settings"]))
    return out


def lookup(rules_of, scope, key):
    best = None
    for depth, index, selector, settings in rules_of:
        if key in settings and (scope == selector or scope.startswith(selector + ".")):
            if best is None or (depth, index) > best[:2]:
                best = (depth, index, settings[key])
    return best[2] if best else None


def paint(color):
    return "Paint::Rgb(%d, %d, %d)" % tuple(int(color[i : i + 2], 16) for i in (1, 3, 5))


lines = [
    "//! The scopes of the six model-named themes the oracle bundles",
    "//! (`codex-rs/tui/assets/themes/*.tmTheme`), read as `scopes.rs` is read; generated by",
    "//! `tools/rtwk-port/w2-status/model_themes.py`. `codex.accent` is the scope the accent reads.",
    "",
    "use super::{Paint, Scopes};",
    "",
    "pub(super) const THEMES: &[(&str, Scopes)] = &[",
]
for name in THEMES:
    rules_of = rules(plistlib.loads((ROOT / f"tui/assets/themes/{name}.tmTheme").read_bytes()))
    lines += [f'    (\n        "{name}",\n        Scopes {{\n            fg: &[']
    for scope in FG:
        color = lookup(rules_of, scope, "foreground")
        if color:
            lines.append(f'                ("{scope}", {paint(color)}),')
    lines.append("            ],\n            bg: &[")
    for scope in BG:
        color = lookup(rules_of, scope, "background")
        if color:
            lines.append(f'                ("{scope}", {paint(color)}),')
    lines.append("            ],\n        },\n    ),")
lines.append("];")
OUT.write_text("\n".join(lines) + "\n")
